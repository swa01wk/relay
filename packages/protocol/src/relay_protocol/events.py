"""RP event catalog (PRD §8.1)."""

from enum import StrEnum

PROTOCOL_VERSION = "0.1.0"


class EventType(StrEnum):
    """All representative RP events grouped by family."""

    # Session
    SESSION_STARTED = "SESSION_STARTED"
    SESSION_READY = "SESSION_READY"
    SESSION_ENDED = "SESSION_ENDED"
    SESSION_ERROR = "SESSION_ERROR"

    # Turn
    TURN_STARTED = "TURN_STARTED"
    USER_SPEECH_STARTED = "USER_SPEECH_STARTED"
    USER_SPEECH_ENDED = "USER_SPEECH_ENDED"
    TURN_PROCESSING = "TURN_PROCESSING"
    TURN_COMPLETED = "TURN_COMPLETED"

    # Transcript
    TRANSCRIPT_DELTA = "TRANSCRIPT_DELTA"
    TRANSCRIPT_FINAL = "TRANSCRIPT_FINAL"

    # Response
    RESPONSE_STARTED = "RESPONSE_STARTED"
    RESPONSE_DELTA = "RESPONSE_DELTA"
    RESPONSE_COMPLETED = "RESPONSE_COMPLETED"
    RESPONSE_CANCELLED = "RESPONSE_CANCELLED"

    # Speech
    SPEECH_STARTED = "SPEECH_STARTED"
    SPEECH_PROGRESS = "SPEECH_PROGRESS"
    SPEECH_STOPPED = "SPEECH_STOPPED"

    # Interruption
    INTERRUPTION_DETECTED = "INTERRUPTION_DETECTED"
    RESPONSE_INTERRUPTED = "RESPONSE_INTERRUPTED"
    HEARD_TEXT_COMMITTED = "HEARD_TEXT_COMMITTED"

    # Tools
    TOOL_CALL_STARTED = "TOOL_CALL_STARTED"
    TOOL_CALL_PROGRESS = "TOOL_CALL_PROGRESS"
    TOOL_CALL_COMPLETED = "TOOL_CALL_COMPLETED"
    TOOL_CALL_FAILED = "TOOL_CALL_FAILED"

    # UI actions
    ACTION_REQUESTED = "ACTION_REQUESTED"
    ACTION_APPLIED = "ACTION_APPLIED"
    ACTION_FAILED = "ACTION_FAILED"

    # State
    STATE_SNAPSHOT = "STATE_SNAPSHOT"
    STATE_DELTA = "STATE_DELTA"
    STATE_VERSION_ADVANCED = "STATE_VERSION_ADVANCED"
    STATE_CONFLICT = "STATE_CONFLICT"

    # Activity
    ACTIVITY_STARTED = "ACTIVITY_STARTED"
    ACTIVITY_PROGRESS = "ACTIVITY_PROGRESS"
    ACTIVITY_COMPLETED = "ACTIVITY_COMPLETED"

    # HITL
    APPROVAL_REQUESTED = "APPROVAL_REQUESTED"
    APPROVAL_GRANTED = "APPROVAL_GRANTED"
    APPROVAL_REJECTED = "APPROVAL_REJECTED"
    COMMIT_STARTED = "COMMIT_STARTED"
    COMMIT_VERIFIED = "COMMIT_VERIFIED"

    # Observability
    TRACE_LINK = "TRACE_LINK"
    METRIC = "METRIC"
    WARNING = "WARNING"
    ERROR = "ERROR"


ALL_EVENT_TYPES: tuple[EventType, ...] = tuple(EventType)
